/**
 * The stages of a project, with its plan merged on.
 *
 * The opening phase is prepended, and each original phase keeps its paragraph
 * as `bodyAr` beneath its new goal, steps and exit condition. A project with no
 * plan yet returns its stages untouched rather than throwing — but the suite
 * asserts there is no such project, so that branch is a safety net and not an
 * accepted state.
 */
export function stagesWithPlan(
  projectId: string, stages: readonly ProjectStageSeed[],
): ProjectStage[] {
  const plan = BUILD_PLANS[projectId];
  // A project without a build plan cannot render a build section, and a build
  // section with empty phases is exactly what this batch replaced. Failing at
  // module load makes that impossible to ship rather than merely unlikely.
  if (!plan) {
    throw new Error(
      `project "${projectId}" has no build plan — add one to BUILD_PLANS in `
      + 'src/data/projects/buildPlans.ts before it can be published',
    );
  }
  return [
    plan.opening,
    ...stages.map((s, i) => {
      const up = plan.upgrades[i];
      // Same reasoning as the missing-plan case above: a phase with no upgrade
      // would render a heading and a paragraph and nothing else, which is the
      // exact shape this batch existed to remove.
      if (!up) {
        throw new Error(
          `project "${projectId}" phase ${i + 1} ("${s.titleAr}") has no plan — `
          + 'BUILD_PLANS.upgrades must have one entry per phase, in order',
        );
      }
      return { ...s, goalAr: up.goalAr, steps: up.steps, doneWhenAr: up.doneWhenAr };
    }),
  ];
}
