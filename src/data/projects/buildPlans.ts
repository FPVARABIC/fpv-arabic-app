import type { ProjectStage, ProjectStageSeed, ProjectStep } from './types';

/**
 * How to build each project, as a plan rather than a description.
 *
 * WHAT WAS WRONG WITH THE OLD SECTION
 * -----------------------------------
 * It was five accurate paragraphs per project, and every one of them started in
 * the middle. «شغّل الكاميرا والنموذج على الحاسوب المرافق» is a correct first
 * instruction only for somebody who already owns a companion computer, already
 * chose which one, and already knows why. A reader meeting the project for the
 * first time could not act on a single line of it — they could only agree that
 * it sounded right.
 *
 * The missing part was the beginning: WHAT DO I CHOOSE, AND WHAT DO I BUY. So
 * every project gains an opening phase that is nothing but decisions, and each
 * of the original phases gains three things it never had — what it is for, what
 * to actually do, and how to know it is finished.
 *
 * WHY THIS IS A SEPARATE FILE
 * ---------------------------
 * The catalogue files hold what each project IS. This holds how it is BUILT,
 * for every project, in one place — so the plans can be read against each other
 * and kept in the same shape. `registry.ts` merges them onto the stages, which
 * means the original paragraph survives as context beneath the steps rather
 * than being thrown away.
 *
 * WHAT IS DELIBERATELY NOT HERE
 * -----------------------------
 * Part numbers, prices and specific models. A plan that names a model is out of
 * date the season after it is written, and this platform has one place for
 * what to buy — the parts list and the shop. Steps name the DECISION and its
 * trade-off; the parts section names the thing.
 */

/** The upgrade applied to one of a project's original phases, in order. */
export interface StageUpgrade {
  goalAr: string;
  steps: ProjectStep[];
  doneWhenAr: string;
}

export interface ProjectBuildPlan {
  /**
   * What the reader ENDS UP WITH, in one concrete sentence.
   *
   * The six questions a first-time reader asks were answered by the page
   * except for the last one: «إلى ماذا سأصل في النهاية؟». `learningOutcomesAr`
   * answers what they will KNOW, which is a different question — somebody
   * deciding whether to spend six weeks and a few hundred euros wants to know
   * what will be sitting on their table at the end.
   *
   * It is deliberately a THING, not a feeling: «طائرة تتابع سيارة متحرّكة»
   * rather than «فهم أعمق للرؤية الحاسوبية». If it cannot be photographed or
   * demonstrated, it is not an end state.
   */
  finishedAr: string;
  /** The choosing-and-gathering phase, prepended to every project. */
  opening: ProjectStage;
  /** One entry per existing stage, in the order they already appear. */
  upgrades: StageUpgrade[];
}

