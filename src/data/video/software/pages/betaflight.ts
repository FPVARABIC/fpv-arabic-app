/**
 * The Betaflight half of the video software centre.
 *
 * WHAT THESE PAGES ARE NOT
 * ------------------------
 * They are not a second copy of the Betaflight reference. `data/betaflight`
 * already owns the OSD tab's 43 fields and the VTX tab's 29, reviewed against a
 * stated version, and duplicating any of that here would give the platform two
 * descriptions of one screen that drift apart on the next release.
 *
 * What these pages own is the part the field reference cannot: the ORDER. Which
 * screen first, what must be true before you open it, what to look at to know
 * it worked, and what to do when it did not. A reader who knows what every
 * field on the OSD tab does can still fail to get an overlay, because the thing
 * that was wrong was on the Ports tab and nothing told them to look there.
 *
 * Every page here links into the field reference rather than restating it, and
 * every page declares which recorded facts it is about so it can show the
 * reader their own port numbers while they work.
 */

