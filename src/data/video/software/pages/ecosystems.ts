/**
 * What genuinely differs between the digital ecosystems' tooling.
 *
 * These three pages exist BECAUSE the shared pages exist. Since installing,
 * backing up, updating, recovering and reading logs are the same procedure
 * everywhere, the only thing left to write per ecosystem is what is actually
 * particular to it — and that turns out to be a short, honest list: which route
 * the firmware travels, whether the two ends must move together, what the
 * closed parts of the system mean for the reader's freedom, and which questions
 * only that manufacturer can answer.
 *
 * WHAT IS DELIBERATELY ABSENT
 * ---------------------------
 * No application names presented as current. No download URLs. No button
 * sequences. No claim that generation X pairs with goggles Y. Every one of
 * those is a fact with a shelf life measured in months, owned by a company that
 * can change it without telling anyone, and getting one wrong here costs the
 * reader hardware rather than time.
 *
 * What each page DOES give is the shape of the system: how closed it is, where
 * the reader will hit a wall, and exactly which page of which manufacturer's
 * site answers the question. That is the part that stays true.
 */

