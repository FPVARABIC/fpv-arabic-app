/**
 * The manufacturer-tool half of the video software centre.
 *
 * THE HARDEST EDITORIAL PROBLEM IN THIS WHOLE SYSTEM
 * -------------------------------------------------
 * Betaflight is open, versioned, and documented in one place, so a page about it
 * can say "open the Ports tab" and be right. The digital video ecosystems are
 * none of those things: their desktop applications get renamed, their update
 * routes change per generation (cable on one, SD card on another, phone app on a
 * third), and their download pages move. A page here that named a button would
 * be right for one reader and would brick the next reader's unit.
 *
 * So these pages are written at the level that does NOT go stale:
 *
 *   what the step accomplishes    — stable, it is the same on every system
 *   why it must come in that order — stable, it follows from how flashing works
 *   what it looks like when wrong  — stable, the failure modes are physics
 *   which button, which menu, which file — NOT stated, declared as missing data
 *
 * That is not a hedge; it is the only honest shape. A reader who understands
 * that a backup taken after a failed flash is worthless, and that a device must
 * not be disconnected mid-write, is protected on every system including ones
 * that did not exist when this was written. A reader handed a button name for
 * the wrong generation is not protected at all.
 *
 * WHY MOST PAGES ARE `scope: 'all'`
 * ---------------------------------
 * Because the procedure genuinely is the same. Writing one backup page per
 * ecosystem would have produced four near-identical files that drift, which is
 * exactly the duplication the platform forbids — and it would have implied a
 * difference where there is none. The three ecosystem pages exist for what
 * actually differs, and they say what differs rather than repeating the shared
 * procedure around it.
 */

