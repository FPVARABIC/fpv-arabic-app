/**
 * المدخلات والمزج والمخارج — the chain from a stick to a channel.
 *
 * EdgeTX moves every command through the same three stages: an INPUT reads a
 * physical control and shapes it, a MIX decides which channel that input feeds
 * and how much, an OUTPUT trims and limits what finally leaves the radio. That
 * order is the invariant these six topics teach, because it is the thing that
 * survives every version change and every radio model — and knowing it is what
 * lets a reader find the right screen even when the menu has moved.
 */

