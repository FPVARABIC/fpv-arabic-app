// Safe string-keyed accessor for the view layer, where a stage id arrives as
// a plain `string` (RoadmapStep.id in ../types is not narrowed to
// RoadmapStageId). The object literal above still gets full compile-time
// exhaustiveness checking against the 10 approved IDs; this only relaxes the
// runtime lookup so an unexpected id renders empty sections instead of
// crashing.
export function getRoadmapStageContent(id: string): RoadmapStageContent {
  return (roadmapStageContent as Record<string, RoadmapStageContent>)[id] ?? EMPTY_STAGE_CONTENT;
}
