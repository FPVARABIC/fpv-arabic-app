/**
 * Video-system diagnostic trees.
 *
 * WHAT THIS FILE DELIBERATELY DOES NOT OWN
 * ----------------------------------------
 * Three video-shaped symptoms already have owners elsewhere, and duplicating
 * them would give the platform two procedures for one fault:
 *
 *   lines in the image that worsen with throttle  →  dx-power-noise
 *   a shaky, wobbling "jello" image               →  dx-prop-vibration
 *   the CONTROL link degrading when video power   →  dx-rc-range
 *     is raised
 *
 * Every tree here that could be confused with one of those says so out loud in
 * a `quickChecks` line and hands over through a link. The rule is the same one
 * the EdgeTX centre follows: one owner per symptom, and the other places link.
 *
 * THE FIRST BRANCH IS ALWAYS ANALOG VERSUS DIGITAL
 * ------------------------------------------------
 * Almost every video fault means something different depending on the link
 * class. "No image" on analog with a working receiver produces snow; on digital
 * it produces black, because there is nothing to decode. A tree that does not
 * split on this early sends half its readers down the wrong path, so the split
 * happens as early as the evidence allows.
 *
 * SAFETY ORDERING
 * ---------------
 * Every path runs visual → electrical → software → functional. The video
 * system adds one hazard the other systems do not have: a transmitter powered
 * with no antenna damages itself in seconds, so several trees check the antenna
 * before they allow any power at all.
 */

